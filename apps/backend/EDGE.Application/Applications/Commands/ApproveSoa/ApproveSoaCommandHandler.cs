using System;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using MediatR;
using EDGE.Domain.Entities;
using EDGE.Domain.Enums;
using EDGE.Application.Common.Models;
using EDGE.Application.Common.Interfaces;

namespace EDGE.Application.Applications.Commands.ApproveSoa;

public class ApproveSoaCommandHandler : IRequestHandler<ApproveSoaCommand, ApiResponse<Guid>>
{
    private readonly IApplicationFullRepository _repository;
    private readonly IUnitOfWork _unitOfWork;
    private readonly ICurrentUserService _currentUserService;
    private readonly IUserRepository _userRepository;
    private readonly INumberingSeriesService? _numberingSeriesService;

    public ApproveSoaCommandHandler(
        IApplicationFullRepository repository,
        IUnitOfWork unitOfWork,
        ICurrentUserService currentUserService,
        IUserRepository userRepository,
        INumberingSeriesService? numberingSeriesService = null)
    {
        _repository = repository;
        _unitOfWork = unitOfWork;
        _currentUserService = currentUserService;
        _userRepository = userRepository;
        _numberingSeriesService = numberingSeriesService;
    }

    public async Task<ApiResponse<Guid>> Handle(ApproveSoaCommand request, CancellationToken cancellationToken)
    {
        StatementOfAccount? soa = null;

        // 1. Resolve SOA by direct SoaId if provided
        if (request.SoaId.HasValue && request.SoaId.Value != Guid.Empty)
        {
            soa = await _repository.GetSoaByIdAsync(request.SoaId.Value, cancellationToken);
        }

        // 2. If SOA not found by direct ID, resolve by ApplicationId (or fallback if SoaId was an ApplicationId)
        if (soa == null)
        {
            var targetAppId = (request.ApplicationId.HasValue && request.ApplicationId.Value != Guid.Empty)
                ? request.ApplicationId.Value
                : (request.SoaId.HasValue && request.SoaId.Value != Guid.Empty ? request.SoaId.Value : Guid.Empty);

            if (targetAppId != Guid.Empty)
            {
                var appLoaded = await _repository.GetByIdWithDetailsAsync(targetAppId, cancellationToken);
                if (appLoaded != null)
                {
                    // Prioritize ForOrderOfPayment SOA, then Pending, then Approved
                    soa = appLoaded.StatementsOfAccount.OrderByDescending(s => s.CreatedAt).FirstOrDefault(s => s.Status == SoaStatus.ForOrderOfPayment || s.Status == SoaStatus.Pending)
                          ?? appLoaded.StatementsOfAccount.OrderByDescending(s => s.CreatedAt).FirstOrDefault(s => s.Status == SoaStatus.Approved);

                    if (soa != null && soa.Application == null)
                    {
                        soa.Application = appLoaded;
                    }
                }
            }
        }

        if (soa == null)
        {
            return ApiResponse<Guid>.Fail("Statement of Account (SOA) not found for this approval request. Please ensure an SOA has been generated by the Evaluator first.");
        }

        var app = soa.Application ?? await _repository.GetByIdWithDetailsAsync(soa.ApplicationId, cancellationToken) ?? await _repository.GetByIdAsync(soa.ApplicationId, cancellationToken);
        if (app == null)
        {
            return ApiResponse<Guid>.Fail("Application not found.");
        }

        // 3. Idempotency Guard: Only short-circuit if SOA is already approved, OP is already billed/active, AND application is already in PendingPayment
        if (soa.Status == SoaStatus.Approved && app.Status == ApplicationStatus.PendingPayment)
        {
            var alreadyApprovedOp = app.OrdersOfPayment.FirstOrDefault(o => o.StatementOfAccountId == soa.Id)
                                    ?? app.OrdersOfPayment.OrderByDescending(o => o.CreatedAt).FirstOrDefault(o => o.Status == OpStatus.Billed || o.Status == OpStatus.Processing || o.Status == OpStatus.Paid);

            if (alreadyApprovedOp != null && alreadyApprovedOp.Status != OpStatus.Returned)
            {
                return ApiResponse<Guid>.Success(alreadyApprovedOp.Id, "Statement of Account and Application are already approved. Existing Order of Payment returned.");
            }
        }

        // 4. Status validation: Application must be in reviewable state (ForAccountant, Evaluating, Submitted, or Returned)
        if (app.Status != ApplicationStatus.ForAccountant &&
            app.Status != ApplicationStatus.Evaluating &&
            app.Status != ApplicationStatus.Submitted &&
            app.Status != ApplicationStatus.Returned &&
            app.Status != ApplicationStatus.PendingPayment)
        {
            return ApiResponse<Guid>.Fail($"Statement of Account cannot be approved because the application is in '{app.Status}' status.");
        }

        var userContext = await _userRepository.GetStaffUserContextAsync(_currentUserService.UserId, "Accountant", cancellationToken);
        Guid? validUserId = null;
        if (userContext.UserId.HasValue && await _repository.UserExistsAsync(userContext.UserId.Value, cancellationToken))
        {
            validUserId = userContext.UserId.Value;
        }

        var staffName = !string.IsNullOrWhiteSpace(userContext.StaffName) ? userContext.StaffName : "Accountant";
        var staffRole = !string.IsNullOrWhiteSpace(userContext.StaffRole) ? userContext.StaffRole : "Accountant";

        var prevSoaStatus = soa.Status;
        soa.Status = SoaStatus.Approved;
        soa.ApprovedByUserId = validUserId;
        soa.ApprovedAt = DateTime.UtcNow;

        var existingOp = app.OrdersOfPayment?.FirstOrDefault(o => o.StatementOfAccountId == soa.Id)
                         ?? app.OrdersOfPayment?.OrderByDescending(o => o.CreatedAt).FirstOrDefault(o => o.Status == OpStatus.Billed || o.Status == OpStatus.Processing || o.Status == OpStatus.Returned);

        OrderOfPayment op;
        if (existingOp != null)
        {
            op = existingOp;
            op.Status = OpStatus.Billed;
            op.AmountDue = soa.TotalAmount;
            op.AmountReceived = 0;
            op.PaymentMethod = null;
            op.CheckNumber = null;
            op.CheckBank = null;
            op.CheckDate = null;
            op.PaidAt = null;
            op.OfficialReceiptNumber = null;
            op.Remarks = "Order of Payment issued. Ready for client payment.";
        }
        else
        {
            op = new OrderOfPayment
            {
                Id = Guid.NewGuid(),
                ApplicationId = soa.ApplicationId,
                StatementOfAccountId = soa.Id,
                OpNumber = _numberingSeriesService != null
                    ? await _numberingSeriesService.GenerateOpNumberAsync(app?.TenantId ?? soa.Application?.TenantId ?? Guid.Empty, cancellationToken)
                    : $"OP-{DateTime.UtcNow:yyyy}-{Guid.NewGuid().ToString()[..6].ToUpper()}",
                AmountDue = soa.TotalAmount,
                Status = OpStatus.Billed,
                CreatedAt = DateTime.UtcNow
            };
            await _repository.AddOpAsync(op, cancellationToken);
        }

        await _repository.AddSoaHistoryAsync(new SoaHistory
        {
            Id = Guid.NewGuid(),
            StatementOfAccountId = soa.Id,
            Action = "SOA approved by Accountant. Order of Payment generated.",
            FromStatus = prevSoaStatus,
            ToStatus = SoaStatus.Approved,
            PerformedByUserId = validUserId,
            StaffName = staffName,
            StaffRole = staffRole,
            Remarks = request.Remarks,
            Timestamp = DateTime.UtcNow
        }, cancellationToken);

        await _repository.AddOpHistoryAsync(new OpHistory
        {
            Id = Guid.NewGuid(),
            OrderOfPaymentId = op.Id,
            Action = "Order of Payment issued.",
            ToStatus = OpStatus.Billed,
            PerformedByUserId = validUserId,
            StaffName = staffName,
            StaffRole = staffRole,
            Timestamp = DateTime.UtcNow
        }, cancellationToken);

        var prevAppStatus = app.Status;
        app.Status = ApplicationStatus.PendingPayment;
        app.Remarks = "SOA approved by Accountant. Order of Payment generated and ready for payment.";
        await _repository.UpdateAsync(app, cancellationToken);

        await _repository.AddApplicationStatusHistoryAsync(new ApplicationStatusHistory
        {
            Id = Guid.NewGuid(),
            ApplicationId = app.Id,
            Status = ApplicationStatus.PendingPayment,
            Remarks = "SOA approved by Accountant. Ready for payment.",
            Timestamp = DateTime.UtcNow,
            UserId = validUserId
        }, cancellationToken);

        await _repository.AddApplicationHistoryAsync(new ApplicationHistory
        {
            Id = Guid.NewGuid(),
            ApplicationId = app.Id,
            Action = "SOA Approved by Accountant",
            FromStatus = prevAppStatus,
            ToStatus = ApplicationStatus.PendingPayment,
            PerformedByUserId = validUserId,
            StaffName = staffName,
            StaffRole = staffRole,
            Remarks = request.Remarks ?? "SOA approved by Accountant. Order of Payment generated.",
            Timestamp = DateTime.UtcNow
        }, cancellationToken);

        await _unitOfWork.SaveChangesAsync(cancellationToken);

        return ApiResponse<Guid>.Success(op.Id, "Statement of Account and Application approved. Order of Payment generated successfully.");
    }
}
